export const HULL_BY_ID = Object.fromEntries(HULLS.map((h) => [h.id, h])) as Record<string, Hull>;

export function rivalFor(id: string) {
  const hull = HULL_BY_ID[id] ?? HULLS[1];
  const same = HULLS.find((h) => h.nation !== hull.nation && h.klass === hull.klass);
  return same ?? HULLS.find((h) => h.nation !== hull.nation) ?? HULLS[0];
}

